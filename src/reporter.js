const fs = require("fs");
const path = require("path");

/**
 * Generate an HTML report from a comparison result and write it to disk.
 *
 * @param {object} report - Comparison report from comparePixels()
 * @param {string} outputPath - File path for the HTML output
 * @param {object[]} [scanResults] - Raw scan results from interceptor (for debug section)
 */
function generateReport(report, outputPath, scanResults) {
  const html = buildHtml(report, scanResults);
  fs.writeFileSync(outputPath, html, "utf-8");
  console.log(`\nReport saved to: ${path.resolve(outputPath)}`);
}

function buildHtml(report, scanResults) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Pixel Comparator Report</title>
<style>
${getStyles()}
</style>
</head>
<body>
<div class="container">
  <header>
    <h1>Pixel Comparator Report</h1>
    <p class="subtitle">TikTok vs Meta/Facebook Pixel Comparison</p>
    <p class="meta">Generated: ${new Date(report.generatedAt).toLocaleString()}</p>
  </header>

  ${renderSummary(report.summary)}

  ${report.pages.map((page, i) => renderPage(page, i)).join("\n")}

  ${scanResults ? renderDebugSection(scanResults) : ""}

  <footer>
    <p>Generated by <strong>pixel-comparator</strong></p>
  </footer>
</div>
</body>
</html>`;
}

