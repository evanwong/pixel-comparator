function renderPage(page, index) {
  // Render per-TikTok-pixel comparison sections (each contains per-Meta-pixel sub-comparisons)
  const pixelSections = page.pixelComparisons.map((pc) =>
    renderPixelComparison(pc)
  ).join("\n");

  // Render Meta-only events (not matched by any TikTok pixel)
  const metaOnlySection = page.metaOnlyEvents && page.metaOnlyEvents.length > 0
    ? renderMetaOnlySection(page.metaOnlyEvents, page.meta)
    : "";

  const redirectNote = page.redirectChain
    ? renderRedirectChain(page.redirectChain)
    : page.originalUrl
      ? `<div class="redirect-notice">Redirected from <a href="${esc(page.originalUrl)}" target="_blank">${esc(page.originalUrl)}</a></div>`
      : "";

  return `
  <section class="page-section">
    <h2>Page ${index + 1}: <a href="${esc(page.url)}" target="_blank">${esc(page.url)}</a></h2>
    ${redirectNote}

    <div class="stats-grid">
      <div class="stat-card tiktok small">
        <div class="stat-value">${page.tiktok.eventCount}</div>
        <div class="stat-label">TikTok Events</div>
        <div class="stat-detail">${page.tiktok.pixelIds.length} pixel ID(s)</div>
      </div>
      <div class="stat-card meta small">
        <div class="stat-value">${page.meta.eventCount}</div>
        <div class="stat-label">Meta Events</div>
        <div class="stat-detail">${page.meta.pixelIds.length} pixel ID(s)</div>
      </div>
    </div>

    ${pixelSections}
    ${metaOnlySection}
    ${renderObservations(page.observations)}
  </section>`;
}

/**
 * Render a redirect chain as a visual hop-by-hop list.
 */
function renderRedirectChain(chain) {
  if (!chain || chain.length < 2) return "";
  const hops = chain.length - 1;
  const steps = chain.map((url, i) => {
    const label = i === 0 ? "Original" : i === chain.length - 1 ? "Final" : `Hop ${i}`;
    return `<div class="redirect-step"><span class="redirect-label">${label}</span> <a href="${esc(url)}" target="_blank">${esc(url)}</a></div>`;
  }).join('<div class="redirect-arrow">&darr;</div>');

  return `
    <div class="redirect-notice">
      <strong>Redirect chain (${hops} hop${hops > 1 ? "s" : ""}):</strong>
      <div class="redirect-chain">${steps}</div>
    </div>`;
}

/**
 * Render a comparison section for a single TikTok pixel, containing
 * sub-sections for each Meta pixel sorted by health score (highest first).
 */
function renderPixelComparison(pc) {
  const metaSections = pc.metaComparisons.map((mc) =>
    renderMetaSubComparison(mc)
  ).join("\n");

  const comparisonCount = pc.metaComparisons.length;
  const subtitle = comparisonCount > 0
    ? `${pc.tiktokEventCount} TikTok event(s) compared against ${comparisonCount} Meta pixel(s) — sorted by match score`
    : `${pc.tiktokEventCount} TikTok event(s) — no Meta pixels to compare against`;

  return `
    <div class="pixel-comparison-section">
      <h3>TikTok Pixel <code>${esc(pc.tiktokPixelId)}</code></h3>
      <p class="pixel-comparison-meta">${subtitle}</p>
      ${comparisonCount === 0 ? '<p class="no-data">No Meta pixels detected on this page.</p>' : ""}
      ${metaSections}
    </div>`;
}

/**
 * Render a sub-comparison for a single Meta pixel within a TikTok pixel group.
 */
function renderMetaSubComparison(mc) {
  return `
      <div class="meta-comparison-subsection">
        <h4>vs Meta Pixel <code>${esc(mc.metaPixelId)}</code>
          <span class="meta-event-count">${mc.metaEventCount} event(s)</span>
        </h4>
        ${renderHealthSummary(mc.health)}
        ${renderEventComparisonTable(mc.eventComparison, mc.paramComparison)}
      </div>`;
}

/**
 * Render a section for Meta-only events that weren't matched by any TikTok pixel.
 */
function renderMetaOnlySection(metaOnlyEvents, meta) {
  const rows = metaOnlyEvents
    .map((e) => {
      const params = e.customData && Object.keys(e.customData).length > 0
        ? e.customData
        : {};
      return `
      <tr class="meta_only">
        <td><strong>${esc(e.eventName)}</strong></td>
        <td>${esc(e.pixelId || "—")}</td>
        <td><span class="badge ${e.eventCategory}">${esc(e.eventCategory)}</span></td>
        <td><code class="params">${esc(JSON.stringify(params, null, 0))}</code></td>
      </tr>`;
    })
    .join("\n");

  return `
    <div class="pixel-comparison-section">
      <h3>Meta-Only Events</h3>
      <p class="pixel-comparison-meta">Events firing on Meta but not matched by any TikTok pixel.</p>
      <div class="table-wrapper">
      <table class="detail-table">
        <thead><tr><th>Event</th><th>Pixel ID</th><th>Category</th><th>Parameters</th></tr></thead>
        <tbody>${rows}</tbody>
      </table>
      </div>
    </div>`;
}

