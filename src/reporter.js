function renderEventComparisonTable(comparison, paramComparisons) {
  if (comparison.mapped.length === 0) {
    return `<p class="no-data">No events to compare.</p>`;
  }

  // Index param comparisons by event name for fast lookup
  const paramsByEvent = {};
  for (const pc of paramComparisons) {
    paramsByEvent[pc.eventName] = pc;
    if (pc.metaEquivalent && pc.metaEquivalent !== pc.eventName) {
      paramsByEvent[pc.metaEquivalent] = pc;
    }
  }

  const rows = comparison.mapped
    .map((m) => {
      const statusClass = m.status;
      const statusLabel = {
        matched: "Matched",
        count_mismatch: "Count Mismatch",
        tiktok_only: "TikTok Only",
        meta_only: "Meta Only",
      }[m.status];

      // Build the event row
      let html = `
      <tr class="event-row ${statusClass}">
        <td>${esc(m.tiktokEvent || "—")}</td>
        <td>${m.tiktokCount}</td>
        <td>${esc(m.metaEvent || "—")}</td>
        <td>${m.metaCount}</td>
        <td><span class="badge ${statusClass}">${statusLabel}</span></td>
        <td>${esc(m.note)}</td>
      </tr>`;

      // Find param comparison for this event
      const pc = paramsByEvent[m.tiktokEvent] || paramsByEvent[m.metaEvent];
      if (pc) {
        const paramHtml = renderInlineParams(pc);
        if (paramHtml) {
          html += `
      <tr class="param-subrow">
        <td colspan="6">${paramHtml}</td>
      </tr>`;
        }
      }

      return html;
    })
    .join("\n");

  return `
    <h3>Event &amp; Parameter Comparison</h3>
    <div class="table-wrapper">
    <table class="comparison-table">
      <thead>
        <tr>
          <th>TikTok Event</th>
          <th>Count</th>
          <th>Meta Event</th>
          <th>Count</th>
          <th>Status</th>
          <th>Notes</th>
        </tr>
      </thead>
      <tbody>
        ${rows}
      </tbody>
    </table>
    </div>`;
}

/**
 * Render parameter comparison as an expandable details block for inline use
 * inside the event comparison table.
 */
function renderInlineParams(pc) {
  const totalParams = pc.matches.length + pc.differences.length + pc.tiktokOnly.length + pc.metaOnly.length;
  if (totalParams === 0) return null;

  // Compute match percentage
  const matchPct = Math.round((pc.matches.length / totalParams) * 100);
  const pctClass = matchPct >= 80 ? "pct-good" : matchPct >= 50 ? "pct-fair" : "pct-poor";

  // Build summary label
  const parts = [];
  if (pc.matches.length > 0) parts.push(`${pc.matches.length} matched`);
  if (pc.differences.length > 0) parts.push(`${pc.differences.length} different`);
  if (pc.tiktokOnly.length > 0) parts.push(`${pc.tiktokOnly.length} TikTok-only`);
  if (pc.metaOnly.length > 0) parts.push(`${pc.metaOnly.length} Meta-only`);
  const summaryText = `<span class="param-pct ${pctClass}">${matchPct}%</span> param match — ${totalParams} parameter(s): ${parts.join(", ")}`;

  // Build param rows
  let paramRows = "";

  // Differences first (most important)
  for (const d of pc.differences) {
    paramRows += `
            <tr class="diff">
              <td><code>${esc(d.tiktokKey)}</code></td>
              <td class="val">${esc(String(d.tiktokValue))}</td>
              <td><code>${esc(d.metaKey)}</code></td>
              <td class="val">${esc(String(d.metaValue))}</td>
              <td><span class="badge count_mismatch">Different</span></td>
            </tr>`;
  }

  // TikTok-only params
  for (const p of pc.tiktokOnly) {
    paramRows += `
            <tr class="tiktok_only">
              <td><code>${esc(p.key)}</code></td>
              <td class="val">${esc(String(p.value))}</td>
              <td class="empty">—</td>
              <td class="empty">—</td>
              <td><span class="badge tiktok_only">TikTok Only</span></td>
            </tr>`;
  }

  // Meta-only params
  for (const p of pc.metaOnly) {
    paramRows += `
            <tr class="meta_only">
              <td class="empty">—</td>
              <td class="empty">—</td>
              <td><code>${esc(p.key)}</code></td>
              <td class="val">${esc(String(p.value))}</td>
              <td><span class="badge meta_only">Meta Only</span></td>
            </tr>`;
  }

  // Matched params last
  for (const m of pc.matches) {
    paramRows += `
            <tr class="match">
              <td><code>${esc(m.tiktokKey)}</code></td>
              <td class="val">${esc(String(m.value))}</td>
              <td><code>${esc(m.metaKey)}</code></td>
              <td class="val">${esc(String(m.value))}</td>
              <td><span class="badge matched">Same</span></td>
            </tr>`;
  }

  return `
          <details class="param-details">
            <summary>${summaryText}</summary>
            <table class="param-table">
              <thead>
                <tr>
                  <th>TikTok Param</th>
                  <th>TikTok Value</th>
                  <th>Meta Param</th>
                  <th>Meta Value</th>
                  <th>Status</th>
                </tr>
              </thead>
              <tbody>${paramRows}
              </tbody>
            </table>
          </details>`;
}

/**
 * Render a debug section showing all raw intercepted network requests
 * with their parameters in easy-to-read tables.
 */
function renderDebugSection(scanResults) {
  const pages = scanResults.map((result, i) => {
    const tiktokRows = result.tiktokRequests.map((r) => renderDebugRequest(r)).join("\n");
    const metaRows = result.metaRequests.map((r) => renderDebugRequest(r)).join("\n");
    const totalRequests = result.tiktokRequests.length + result.metaRequests.length;

    return `
      <div class="debug-page">
        <h3>Page ${i + 1}: <a href="${esc(result.url)}" target="_blank">${esc(result.url)}</a>
          <span class="debug-count">${totalRequests} request(s)</span>
        </h3>

        <h4 class="debug-platform tiktok">TikTok <span class="debug-count">${result.tiktokRequests.length}</span></h4>
        ${result.tiktokRequests.length > 0 ? tiktokRows : '<p class="no-data">No TikTok requests captured.</p>'}

        <h4 class="debug-platform meta">Meta <span class="debug-count">${result.metaRequests.length}</span></h4>
        ${result.metaRequests.length > 0 ? metaRows : '<p class="no-data">No Meta requests captured.</p>'}
      </div>`;
  }).join("\n");

  return `
  <section class="debug-section">
    <details>
      <summary><h2>Debug: Raw Network Requests</h2></summary>
      <p class="debug-intro">All intercepted pixel network calls with full parameter details.</p>
      ${pages}
    </details>
  </section>`;
}

/**
 * Render a single raw network request as a collapsible block with param tables.
 */
function renderDebugRequest(req) {
  const time = req.wallTime
    ? new Date(req.wallTime * 1000).toISOString().replace("T", " ").replace(/\.\d+Z$/, "")
    : "";

  const queryEntries = Object.entries(req.queryParams || {});
  const postEntries = Object.entries(req.postParams || {});

  const queryTable = queryEntries.length > 0
    ? renderParamTable("Query Parameters", queryEntries)
    : "";

  const postTable = postEntries.length > 0
    ? renderParamTable("POST Body", postEntries)
    : "";

  // Build a short summary label from the most identifying params
  const ev = req.queryParams?.ev || req.postParams?.ev || "";
  const label = ev ? `<code class="debug-event">${esc(ev)}</code> ` : "";

  return `
        <details class="debug-request">
          <summary>
            <span class="debug-method">${esc(req.method)}</span>
            ${label}
            <span class="debug-endpoint">${esc(req.endpoint)}</span>
            ${time ? `<span class="debug-time">${esc(time)}</span>` : ""}
          </summary>
          <div class="debug-request-body">
            <div class="debug-url"><strong>URL:</strong> <code>${esc(req.fullUrl)}</code></div>
            ${queryTable}
            ${postTable}
          </div>
        </details>`;
}

/**
 * Render a name-value parameter table for the debug section.
 */
function renderParamTable(title, entries) {
  const rows = entries.map(([key, value]) => {
    const displayValue = typeof value === "object" ? JSON.stringify(value, null, 2) : String(value);
    return `
              <tr>
                <td><code>${esc(key)}</code></td>
                <td><code class="debug-value">${esc(displayValue)}</code></td>
              </tr>`;
  }).join("\n");

  return `
            <div class="debug-param-group">
              <h5>${esc(title)} <span class="debug-count">${entries.length}</span></h5>
              <table class="debug-param-table">
                <thead><tr><th>Parameter</th><th>Value</th></tr></thead>
                <tbody>${rows}</tbody>
              </table>
            </div>`;
}

function renderObservations(observations) {
  if (!observations || observations.length === 0) return "";

  const items = observations
    .map((obs) => {
      const icon = {
        warning: "⚠",
        info: "ℹ",
        gap: "🔍",
        mismatch: "≠",
        param_diff: "≠",
        param_gap: "🔍",
        good: "✓",
        coverage: "📊",
        summary: "📋",
      }[obs.type] || "•";

      return `<li class="obs-${obs.type}"><span class="obs-icon">${icon}</span> ${esc(obs.message)}</li>`;
    })
    .join("\n");

  return `
    <div class="observations">
      <h3>Observations</h3>
      <ul>${items}</ul>
    </div>`;
}

/**
 * Escape HTML special characters to prevent XSS.
 */
function esc(str) {
  if (str === null || str === undefined) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

